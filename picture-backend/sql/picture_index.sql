-- ============================================================
-- 图片向量索引功能
-- 在启动后端之前，请先在 MySQL 中执行本脚本
-- 数据库：application.yml 中配置的 database1
-- ============================================================

-- ----------------------------
-- picture 表新增「向量索引状态」字段
--   0-未索引（公共图库中还没过审的图片）
--   1-已索引
--   2-索引失败（可重试）
-- 注意：本 ALTER 语句只需执行一次，重复执行会提示字段已存在
-- ----------------------------
ALTER TABLE `picture`
    ADD COLUMN `indexStatus` TINYINT NOT NULL DEFAULT 0 COMMENT '向量索引状态：0-未索引 1-已索引 2-索引失败';

-- 便于定时任务快速扫描出失败的记录进行重试
ALTER TABLE `picture`
    ADD INDEX `idx_indexStatus` (`indexStatus`);
